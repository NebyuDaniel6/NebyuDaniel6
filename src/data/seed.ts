function demandDate(
  id: string,
  type: ImportantDate["type"],
  count: number,
): ImportantDate[] {
  const next = addDays(today, 1);
  return Array.from({ length: count }, (_, i) => ({
    id: `${id}-${i}`,
    personId: `${id}-person-${i}`,
    userId: "ext",
    type,
    month: next.getMonth() + 1,
    day: next.getDate(),
    repeatsAnnually: true,
    reminderOffsets: [7],
  }));
}

